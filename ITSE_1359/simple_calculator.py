#Create a basic calculator that performs arithmetic operations on two numbers.

print("Hello there, wanna give my new calculator a try?")
first=(float(input("Enter your first number: ")))
second=(float(input("Enter your second number: \n")))

print(f"{first} + {second} = \n",first+second)
print(f"{first} - {second} = \n",first-second)
print(f"{first} x {second} = \n",first*second)
print(f"{first} / {second} = \n",first/second)
print(f"{first} // {second} = \n",first//second)
print(f"{first} % {second} = \n",first%second)
print(f"{first} ** {second} = \n",first**second)
